def attributed_line(rng, name):
    info = CAST[name]
    line = rng.choice(LINES)
    style = rng.randrange(4)
    verb = rng.choice(info["verbs"])
    if style == 0:
        return f"{name}{verb}：“{line}”"
    if style == 1:
        return f"“{line}”{name}{verb}。"
    if style == 2:
        alias = rng.choice(info["aliases"])
        return f"“{line}”{alias}说。"
    return f"“{line}”"


def templated_chapter(index, title):
    rng = random.Random(index * 7919)
    names = rng.sample(list(CAST.keys()), k=rng.choice([2, 3, 3, 4]))
    parts = [
        f"{rng.choice(NARRATION)}这是青石镇平常的一天，{names[0]}和{names[1]}在茶馆门口碰了面。"
    ]
    for turn in range(rng.randint(10, 14)):
        speaker = names[turn % len(names)]
        parts.append(attributed_line(rng, speaker))
        if turn % 4 == 3:
            parts.append(rng.choice(NARRATION))
    parts.append(f"{names[-1]}没有再说话，只是望着远处。关于“{title}”的这一天，就这样过去了。")
    return "\n\n".join(parts)


