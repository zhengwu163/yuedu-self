def write_book(name, author, intro, chapters, subdir=""):
    target_dir = os.path.join(OUT_DIR, subdir)
    os.makedirs(target_dir, exist_ok=True)
    path = os.path.join(target_dir, f"《{name}》作者：{author}.txt")
    lines = [f"《{name}》", f"作者：{author}", f"简介：{intro}", ""]
    for i, (title, body) in enumerate(chapters, start=1):
        lines.append(f"第{i}章 {title}")
        lines.append("")
        lines.append(body.strip())
        lines.append("")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    return path, len(chapters), sum(len(b) for _, b in chapters)


